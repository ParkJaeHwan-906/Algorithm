SELECT
    T.ID,
    F.FISH_NAME,
    T.LENGTH
FROM (
    SELECT 
        RANK() OVER (PARTITION BY FISH_TYPE ORDER BY LENGTH DESC) AS RNK,
        ID,
        FISH_TYPE,
        LENGTH,
        TIME
    FROM FISH_INFO  
) T
JOIN FISH_NAME_INFO F ON T.FISH_TYPE = F.FISH_TYPE
WHERE T.RNK = 1
ORDER BY T.ID ASC