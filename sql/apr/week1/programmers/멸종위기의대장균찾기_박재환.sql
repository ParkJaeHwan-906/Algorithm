-- 각 대장균이 어느 세대에 포함되는지 --
WITH RECURSIVE ECOLI_GEN AS (
    -- 시작점
    SELECT 
        ID,
        PARENT_ID,
        1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    -- 재귀 확장
    SELECT
        E.ID,
        E.PARENT_ID,
        G.GENERATION + 1 AS GENERATION
    FROM ECOLI_DATA E
    JOIN ECOLI_GEN G ON E.PARENT_ID = G.ID
)

SELECT COUNT(*) AS `COUNT`, GENERATION FROM ECOLI_GEN G
WHERE NOT EXISTS (
    SELECT 1 
    FROM ECOLI_DATA E
    WHERE E.PARENT_ID = G.ID
)
GROUP BY GENERATION 
ORDER BY GENERATION;