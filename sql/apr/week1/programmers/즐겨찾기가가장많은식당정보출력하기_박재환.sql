SELECT 
    T.FOOD_TYPE,
    T.REST_ID,
    T.REST_NAME,
    T.FAVORITES
FROM (
    SELECT 
        RANK() OVER (PARTITION BY FOOD_TYPE ORDER BY FAVORITES DESC) AS RNK,
        FOOD_TYPE,
        REST_ID,
        REST_NAME,
        FAVORITES
    FROM REST_INFO
) T
WHERE T.RNK = 1
ORDER BY T.FOOD_TYPE DESC;