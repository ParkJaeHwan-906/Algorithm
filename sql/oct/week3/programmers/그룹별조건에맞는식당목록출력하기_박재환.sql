WITH USER_REVIEW_COUNT AS (
    SELECT
        MEMBER_ID,
        COUNT(*) AS REVIEW_CNT
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
),
     USER_REVIEW_RNK AS (
         SELECT
             RANK() OVER (ORDER BY REVIEW_CNT DESC) AS RNK,
             MEMBER_ID
         FROM USER_REVIEW_COUNT
     )

SELECT
    MP.MEMBER_NAME,
    RR.REVIEW_TEXT,
    DATE_FORMAT(RR.REVIEW_DATE, '%Y-%m-%d') AS REVIEW_DATE
FROM USER_REVIEW_RNK URR
         JOIN MEMBER_PROFILE MP ON URR.MEMBER_ID = MP.MEMBER_ID
         JOIN REST_REVIEW RR ON RR.MEMBER_ID = URR.MEMBER_ID
WHERE URR.RNK = 1
ORDER BY RR.REVIEW_DATE ASC, RR.REVIEW_TEXT
